//! The level definitions.

use crate::core::enemies::EnemyKind;

#[derive(Clone, Copy, Debug)]
pub struct Level {
    pub crystals: i32,
    pub mines: i32,
    pub max_smart_bombs: i32,
    /// Chance of each extra smart bomb appearing.
    pub smart_bomb_prob: f64,
    /// Points needed for the next extra life.
    pub bonus_life_score: i64,
    pub max_enemies: i32,
    /// Chance per frame and enemy kind of an enemy being released.
    pub enemy_release_prob: f64,
    pub gate_width: i32,
    /// Gate speed in 1/64 pixel per frame.
    pub gate_speed: i32,
    pub gate_change_dir_prob: f64,
    /// Par time in seconds.
    pub par_time: i32,
    /// Percentage chance of each kind of enemy being released, by [`EnemyKind::index`].
    enemy_odds: [u8; 19],
}

impl Level {
    pub fn enemy_odds(&self, kind: EnemyKind) -> i32 {
        self.enemy_odds[kind.index()] as i32
    }
}

