//! The kinds of enemy and their behaviour.

use crate::core::sound::Sound;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum EnemyKind {
    /// Shown as a crystal; touching it gives a random power-up.
    PowerCharge,
    /// The explosion left when something is destroyed. It does not collide.
    Explosion,
    Grunger,
    Zippo,
    Zinger,
    Vince,
    /// Never released by any level.
    Unused,
    Miner,
    Meeby,
    Retaliator,
    Terrier,
    Doinger,
    Snipe,
    Tribbler,
    Tribble,
    Buckshot,
    Cluster,
    Sticktight,
    Repulsor,
}

impl EnemyKind {
    pub const ALL: [EnemyKind; 19] = [
        EnemyKind::PowerCharge,
        EnemyKind::Explosion,
        EnemyKind::Grunger,
        EnemyKind::Zippo,
        EnemyKind::Zinger,
        EnemyKind::Vince,
        EnemyKind::Unused,
        EnemyKind::Miner,
        EnemyKind::Meeby,
        EnemyKind::Retaliator,
        EnemyKind::Terrier,
        EnemyKind::Doinger,
        EnemyKind::Snipe,
        EnemyKind::Tribbler,
        EnemyKind::Tribble,
        EnemyKind::Buckshot,
        EnemyKind::Cluster,
        EnemyKind::Sticktight,
        EnemyKind::Repulsor,
    ];

    pub fn index(self) -> usize {
        self as usize
    }

    pub fn info(self) -> &'static EnemyKindInfo {
        &ENEMY_KINDS[self as usize]
    }

    /// What a destroyed enemy of this kind splits into, if it `tribbles`.
    pub fn offspring(self) -> EnemyKind {
        EnemyKind::ALL[self as usize + 1]
    }

    /// File name stem of the sprite strip.
    pub fn file_name(self) -> String {
        format!("{self:?}").to_lowercase()
    }
}

/// How an enemy kind behaves. Speeds are in 1/64 pixel per frame and probabilities are
/// per frame.
#[derive(Clone, Copy, Debug)]
pub struct EnemyKindInfo {
    pub name: &'static str,
    /// Random velocities are `rand(speed) - speed_offset` in each axis.
    pub speed: i32,
    pub speed_offset: i32,
    /// Random curvature is `rand(curve) - curve_offset`, as the sine of the turn per frame
    /// scaled by 32767.
    pub curve: i32,
    pub curve_offset: i32,
    pub hits: i32,
    pub missile: Option<EnemyMissileKind>,
    pub score: i32,
    pub death_sound: Option<Sound>,

    pub fires: bool,
    pub follows: bool,
    pub curves: bool,
    pub explodes: bool,
    pub lays_mines: bool,
    pub shoots_back: bool,
    /// Rushes at the ship when it is nearly stationary.
    pub zooms: bool,
    /// Always moves at full speed in a random direction.
    pub fixed_speed: bool,
    /// Is knocked back rather than destroyed by bullets.
    pub rebounds: bool,
    /// Splits into its offspring when destroyed.
    pub tribbles: bool,
    pub repulses: bool,

    pub fire_prob: f64,
    pub change_dir_prob: f64,
    pub change_curve_prob: f64,
    pub follow_prob: f64,
    /// Number of animation frames.
    pub frames: usize,
    /// Animation speed in 1/256 frame per frame.
    pub frame_speed: i32,
}

