/// The kinds of enemy missile, named after the enemy that fires them.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EnemyMissileKind {
    Zinger,
    Buckshot,
    Retaliator,
    Doinger,
    Snipe,
    Cluster,
}

impl EnemyMissileKind {
    pub const ALL: [EnemyMissileKind; 6] = [
        EnemyMissileKind::Zinger,
        EnemyMissileKind::Buckshot,
        EnemyMissileKind::Retaliator,
        EnemyMissileKind::Doinger,
        EnemyMissileKind::Snipe,
        EnemyMissileKind::Cluster,
    ];

    pub fn index(self) -> usize {
        self as usize
    }

    pub fn info(self) -> EnemyMissileInfo {
        use EnemyMissileKind::*;

        let (speed, sound, rebounds, aimed) = match self {
            Zinger => (120, Some(Sound::Fire6), false, false),
            Buckshot => (150, Some(Sound::Fire5), false, false),
            Retaliator => (200, Some(Sound::Retaliate), false, true),
            Doinger => (150, None, true, false),
            Snipe => (150, Some(Sound::Fire4), false, true),
            Cluster => (170, None, false, false),
        };

        EnemyMissileInfo {
            speed,
            sound,
            rebounds,
            aimed,
        }
    }

    pub fn file_name(self) -> String {
        format!("{self:?}").to_lowercase()
    }
}

#[derive(Clone, Copy, Debug)]
pub struct EnemyMissileInfo {
    pub speed: i32,
    pub sound: Option<Sound>,
    /// Bounces off the walls instead of disappearing.
    pub rebounds: bool,
    /// Fired at the ship rather than in a random direction.
    pub aimed: bool,
}
